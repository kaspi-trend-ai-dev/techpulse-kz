import {test} from 'node:test';
import {strict as assert} from 'node:assert';
import {editorialQualityIssues} from './editorial-quality.mjs';
test('Rejects repeated marketing filler', () => {
  const a={sections:[{heading:'Amazon Blink',paragraphs:[
    'Amazon представил пять новых камер Blink для дома и домашней безопасности. Устройства предназначены для разных сценариев использования и будут доступны покупателям.',
    'Появление новых моделей расширяет возможности пользователей при выборе системы.',
    'Обновление отражает стремление компании предлагать новые решения, которые могут заинтересовать потребителей.',
    'Представленные продукты могут заинтересовать покупателей, которые выбирают аппаратуру для дома и квартиры.'
  ]}]};
  assert.ok(editorialQualityIssues(a).some(x=>x.includes('filler')));
});
test('Accepts detailed, evidence-checkable reporting', () => {
  const a={sections:[{heading:'Результат матча',paragraphs:[
    'Александр Бублик победил Карена Хачанова после трёх сетов со счётом 4:6, 7:6 (7:5), 7:6 (7:5). Встреча длилась 2 часа 28 минут и завершилась выходом казахстанца в полуфинал Almaty Open.',
    'Следующим соперником Бублика станет Даниил Медведев. Турнир категории ATP 250 проводится на «Алматы Арене» с 17 по 25 октября, а призовой фонд составляет 1,07 миллиона долларов.',
    'В четвертьфинале Бублик уступил первый сет, но выиграл два последующих на тай-брейках. Именно эти два отрезка матча определили итоговый результат и выход в следующий круг турнира.'
  ]}]};
  assert.deepEqual(editorialQualityIssues(a),[]);
});
